import { AlignmentType, BorderStyle, Document, HeadingLevel, Packer, Paragraph, ShadingType, Table, TableCell, TableRow, TextRun, WidthType } from "docx";

const exampleIdx = process.argv.indexOf("--example");
const EXAMPLE = exampleIdx !== -1;
const OUT = EXAMPLE ? process.argv[exampleIdx + 1] : path.join(process.cwd(), "public", "templates");

const FONT = "Calibri";
const GREY = "6F6D68";
const border = { style: BorderStyle.SINGLE, size: 4, color: "C3C2B7" };
const borders = { top: border, bottom: border, left: border, right: border };

const text = (t, opts = {}) => new TextRun({ text: t, font: FONT, size: 22, ...opts });
const p = (t, opts = {}) => new Paragraph({ children: [text(t, opts)], spacing: { after: 80 } });
const hint = (t) => new Paragraph({ children: [text(`[${t}]`, { italics: true, color: GREY })], spacing: { after: 120 } });
const label = (t) => new Paragraph({ children: [text(t, { bold: true })], spacing: { before: 200, after: 80 } });
const bullet = (t) => new Paragraph({ children: [text(t, EXAMPLE ? {} : { italics: true, color: GREY })], bullet: { level: 0 } });
const heading = (t) => new Paragraph({ heading: HeadingLevel.HEADING_2, children: [text(t, { bold: true, size: 28 })], spacing: { before: 320, after: 120 } });

function cell(t, { head = false, width } = {}) {
  return new TableCell({
    borders,
    width: { size: width, type: WidthType.PERCENTAGE },
    shading: head ? { type: ShadingType.CLEAR, color: "auto", fill: "F0EFEC" } : undefined,
    children: [new Paragraph({ children: [text(t, head ? { bold: true } : {})] })],
  });
}

function table(headers, rows) {
  const widths = headers.length === 3 ? [56, 22, 22] : headers.map(() => Math.floor(100 / headers.length));
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, { head: true, width: widths[i] })) }),
      ...rows.map((r) => new TableRow({ children: r.map((c, i) => cell(c, { width: widths[i] })) })),
    ],
  });
}

/** rows: [назва, одиниця, приклад значення] */
const kpiTable = (rows) => table(["Показник", "Значення", "Одиниця"], rows.map(([n, u, v]) => [n, EXAMPLE ? v : "", u]));

function block(title, hints, examples) {
  return [label(title), ...(EXAMPLE ? examples : hints.map((h) => `[${h}]`)).map(bullet)];
}

function header(title) {
  return [
    new Paragraph({ alignment: AlignmentType.LEFT, children: [text(title, { bold: true, size: 32 })], spacing: { after: 160 } }),
    p(`Філія: ${EXAMPLE ? "Житомир" : "[назва філії]"}`),
    p(`Період: ${EXAMPLE ? "26.10.2026 - 01.11.2026" : "[дд.мм.рррр] - [дд.мм.рррр]"}`),
    p(`Звіт підготував(ла): ${EXAMPLE ? "Марина Ковальчук" : "[ПІБ]"}`),
    ...(EXAMPLE
      ? []
      : [
          hint(
            "Як заповнювати: вписуйте числа лише в колонку Значення (1 115 або 40,01; час на лінії як 1:34). Порожні рядки таблиці просто пропускаються. Підказки в квадратних дужках замініть своїм текстом або видаліть. Назви показників не змінюйте: так додаток порівнює тижні між собою.",
          ),
        ]),
  ];
}

