export function documentsBlock(docs: Doc[]): string {
  return docs.map((d) => `<document name="${d.name.replace(/"/g, "'")}">\n${d.text}\n</document>`).join("\n\n");
}

export function kpiHint(knownKpis: string[]): string {
  return knownKpis.length
    ? `\n\nНазви KPI з попередніх тижнів (формат "Відділ: показник"), використовуй їх для тих самих показників:\n${knownKpis.slice(0, 300).join("\n")}`
    : "";
}

/**
 * Повний запит для вставки в claude.ai (підписка, без API): інструкції, JSON-схема відповіді і дані.
 */
export function chatPrompt(system: string, schema: z.ZodType, task: string): string {
  const jsonSchema = JSON.stringify(z.toJSONSchema(schema), null, 1);
  return `${system}

Формат відповіді: поверни ЛИШЕ один JSON-об'єкт, що відповідає цій JSON-схемі, без пояснень і без markdown. Його вставлять у програму автоматично.
<json_schema>
${jsonSchema}
</json_schema>

${task}`;
}

/** Розбирає відповідь Claude з чату: JSON може бути в ```json ... ``` або з текстом навколо. */
export function parseChatAnswer<T>(text: string, schema: z.ZodType<T>): { ok: true; value: T } | { ok: false; error: string } {
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  if (start === -1 || end <= start) return { ok: false, error: "У відповіді не знайдено JSON. Скопіюйте відповідь Claude повністю." };
  let data: unknown;
  try {
    data = JSON.parse(text.slice(start, end + 1));
  } catch {
    return { ok: false, error: "JSON у відповіді пошкоджений або обрізаний. Попросіть Claude повторити відповідь повністю." };
  }
  const parsed = schema.safeParse(data);
  if (!parsed.success) {
    const issue = parsed.error.issues[0];
    return { ok: false, error: `Відповідь не відповідає формату (${issue.path.join(".") || "корінь"}: ${issue.message}). Попросіть Claude дотримуватись JSON-схеми.` };
  }
  return { ok: true, value: parsed.data };
}
